/* current language: set per page before this file loads */
const LANG = (typeof document !== 'undefined' && document.documentElement.dataset.lang) || 'en';

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(vars[k]);
  return s;
}

if (typeof window !== 'undefined') window.I18N = I18N;   // module scripts read this
if (typeof module !== 'undefined') module.exports = { I18N, LANGS, t };
